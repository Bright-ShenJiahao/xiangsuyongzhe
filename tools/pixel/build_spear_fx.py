"""Validate and pack the supplied 2x spear VFX, without recropping frames.

Optional argument: ZIP archive. Only explicitly named PNGs are imported.
The fourth dragon-breath asset is stored as a reserve, not a new damage effect.
"""
from pathlib import Path
from zipfile import ZipFile
import io
import json
import sys
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'art/src/spearfx'
DEST = ROOT / 'art/fx/player/spear'
NAMES = ['thrust', 'sweep', 'javelin', 'rapid', 'rising', 'drill',
         'leap_impact', 'thunder_ray', 'dragon_soul', 'meteor', 'return',
         'knight_charge', 'impact', 'dragon_breath']
PALETTES = {
    'silver': ['233449', '69899B', 'C5D9DF', 'F1F3E5'],
    'gold': ['36302E', '917445', 'D8B970', 'F5EDC3'],
    'thunder': ['294A63', '568DB5', '9EDFE8', 'F1F3E5'],
    'dragon': ['234943', '4B8C79', '8DD1B0', 'E3F0D2'],
}
ANCHORS = {'thrust': [8, 32], 'sweep': [12, 32], 'rapid': [8, 32],
           'rising': [8, 36], 'thunder_ray': [8, 32], 'meteor': [32, 54],
           'return': [8, 32], 'knight_charge': [8, 32], 'dragon_breath': [12, 32]}


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    DEST.mkdir(parents=True, exist_ok=True)
    if len(sys.argv) > 1:
        with ZipFile(sys.argv[1]) as archive:
            members = {Path(n).name: n for n in archive.namelist() if n.endswith('.png')}
            for name in NAMES:
                filename = 'spear_' + name + '.png'
                data = archive.read(members[filename])
                Image.open(io.BytesIO(data)).verify()
                (SRC / filename).write_bytes(data)
    result = {}
    for name in NAMES:
        filename = 'spear_' + name + '.png'
        image = Image.open(SRC / filename).convert('RGBA')
        assert image.size == (512, 128), filename
        a = np.array(image)
        assert set(np.unique(a[:, :, 3])) <= {0, 255}, filename
        small = a[::2, ::2]
        assert np.array_equal(a, small.repeat(2, 0).repeat(2, 1)), filename
        palette = 'gold' if name in ['impact', 'knight_charge'] else 'thunder' if name in ['drill', 'leap_impact', 'thunder_ray'] else 'dragon' if name in ['dragon_soul', 'dragon_breath'] else 'silver'
        allowed = {tuple(bytes.fromhex(c)) for c in PALETTES[palette]}
        assert {tuple(c) for c in small[small[:, :, 3] > 0, :3]} <= allowed, filename
        extents = []
        anchor = ANCHORS.get(name, [32, 32])
        for i in range(4):
            mask = small[:, i*64:(i+1)*64, 3] > 0
            yy, xx = np.where(mask)
            assert len(xx) and min(xx) >= 4 and max(xx) <= 59 and min(yy) >= 4 and max(yy) <= 59, filename
            extents.append({'bbox': [int(xx.min()), int(yy.min()), int(xx.max())+1, int(yy.max())+1],
                            'radius': round(float(np.hypot(xx-anchor[0], yy-anchor[1]).max()), 4)})
        Image.fromarray(small).save(DEST / filename)
        result[name] = {'file': filename, 'size': 64, 'frames': 4, 'anchor': anchor, 'extent': extents}
    (DEST / 'manifest.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    (ROOT / 'js/spearfxdata.js').write_text('// Generated by tools/pixel/build_spear_fx.py\nwindow.SPEAR_FX_ART=' + json.dumps(result, separators=(',', ':')) + ';\n', encoding='utf-8')
    print('Spear VFX: 14 sheets / 56 frames; dimensions, binary alpha, palettes, 2x pixels and margins: PASS')


if __name__ == '__main__':
    main()
