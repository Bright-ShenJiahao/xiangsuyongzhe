def main():
    src=ROOT/'art/src/stafffx';dest=ROOT/'art/fx/player/staff'
    src.mkdir(parents=True,exist_ok=True);dest.mkdir(parents=True,exist_ok=True)
    if len(sys.argv)>1:
        for name,filename,_ in ITEMS:shutil.copy2(Path(sys.argv[1])/(filename+'.webp'),src/(name+'.webp'))
    meta={}
    for name,_,palette in ITEMS:
        original=Image.open(src/(name+'.webp')).convert('RGBA')
        assert original.width==4*original.height
        # The exact same transform is applied to all four cells: no tight recentering.
        small=original.resize((256,64),Image.Resampling.NEAREST)
        raw=np.array(small); pal=np.array([list(bytes.fromhex(c)) for c in PALETTES[palette]])
        rgb=raw[:,:,:3].astype(int)
        nearest=((rgb[:,:,None,:]-pal[None,None,:,:])**2).sum(3).argmin(2)
        raw[:,:,:3]=pal[nearest];raw[:,:,3]=np.where(raw[:,:,3]>=128,255,0)
        source=Image.fromarray(raw)
        out=Image.new('RGBA',(256,64));ext=[]
        union=[]
        for i in range(4):
            cell=source.crop((i*64,0,i*64+64,64));a=np.array(cell);yy,xx=np.where(a[:,:,3]>0)
            assert len(xx)
            union.append([int(xx.min()),int(yy.min()),int(xx.max()+1),int(yy.max()+1)])
        anchor=[32,32]
        if name in ['holy_pillar','thunder_bolt','icewall']:anchor=[32,max(b[3] for b in union)]
        elif name=='abyss_tentacle':anchor=[6,max(b[3] for b in union)]
        elif name=='shadow_fog':anchor=[32,(min(b[1] for b in union)+max(b[3] for b in union))/2]
        elif name=='chain_lightning':anchor=[8,32]
        elif name=='fire_wave':anchor=[8,max(b[3] for b in union)]
        for i in range(4):
            cell=source.crop((i*64,0,i*64+64,64)).resize((56,56),Image.Resampling.NEAREST)
            out.paste(cell,(i*64+4,4));a=np.array(cell);yy,xx=np.where(a[:,:,3]>0);xx=xx+4;yy=yy+4
            ext.append({'bbox':[int(xx.min()),int(yy.min()),int(xx.max()+1),int(yy.max()+1)]})
        newanchor=[anchor[0]*.875+4,anchor[1]*.875+4]
        for e in ext:
            l,t,r,b=e['bbox'];e['radius']=round(max(np.hypot(x-newanchor[0],y-newanchor[1]) for x in [l,r] for y in [t,b]),3)
        out.save(dest/(name+'.png'))
        meta[name]={'file':name+'.png','size':64,'frames':4,'anchor':newanchor,'extent':ext,'palette':palette}
    (dest/'manifest.json').write_text(json.dumps(meta,indent=2),encoding='utf-8')
    (ROOT/'js/stafffxdata.js').write_text('// Generated by tools/pixel/build_staff_fx.py\nwindow.STAFF_FX_ART='+json.dumps(meta,separators=(',',':'))+';\n',encoding='utf-8')
    print('23 sources preserved; 92 frames normalized: binary alpha / four-color palettes / 4px margins')


if __name__=='__main__':main()
