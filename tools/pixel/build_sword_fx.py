"""Pack generated sword FX with shared cell origins, binary alpha and four colors.

No per-frame tight recentering: the source cell origin/ground reference stays fixed.
The approved newmoon sheet is copied byte-for-byte.
"""
from pathlib import Path
import json
import shutil
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage as nd

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'art/src/swordfx'
DEST = ROOT / 'art/fx/player/sword'
COOL = np.array([[35,52,73],[105,137,155],[197,217,223],[241,243,229]])
GOLD = np.array([[54,48,46],[145,116,69],[216,185,112],[245,237,195]])
IDS = ['sword','whirl','guard','wave','phantom','flash','storm','huntingblade','holysword','sworddomain']

def pack(name):
    if name == 'sword':
        shutil.copyfile(ROOT/'art/fx/player/newmoon.png', DEST/'sword.png')
        return Image.open(DEST/'sword.png').convert('RGBA'), [12,32]
    image = Image.open(SRC/(name+'.png')).convert('RGBA')
    width, height = image.size
    cells = [np.array(image.crop((round(i*width/4),0,round((i+1)*width/4),height))) for i in range(4)]
    masks, bounds = [], []
    for a in cells:
        mask = a[:,:,3] >= 210
        lab, _ = nd.label(mask)
        sizes = np.bincount(lab.ravel()); sizes[0] = 0
        # Reject only tiny export specks; keep every substantial disconnected arc/chip.
        mask &= (sizes >= 80)[lab]
        yy, xx = np.where(mask)
        bounds.append([int(xx.min()),int(yy.min()),int(xx.max()+1),int(yy.max()+1)])
        masks.append(mask)
    cx = width / 8
    cy = float(np.median([(b[1]+b[3])/2 for b in bounds]))
    anchor = [32,32]
    if name == 'holysword':
        cy = max(b[3] for b in bounds[1:]) - 1
        scale = 46 / (cy - min(b[1] for b in bounds))
        anchor = [32,56]
    elif name == 'flash':
        cx = width / 4 * .15
        scale = min(44/max(b[2]-cx for b in bounds), 26/max(max(abs(b[1]-cy),abs(b[3]-cy)) for b in bounds))
        anchor = [12,32]
    elif name in ('guard','huntingblade'):
        scale = min(48/max(b[2]-b[0] for b in bounds),22/max(b[3]-b[1] for b in bounds))
    elif name == 'phantom':
        scale = min(54/(max(b[2] for b in bounds)-min(b[0] for b in bounds)),26/max(b[3]-b[1] for b in bounds))
    else:
        radius = max(np.hypot(np.where(m)[1]-cx,np.where(m)[0]-cy).max() for m in masks)
        scale = 27 / radius
    palette = GOLD if name in ('flash','holysword') else COOL
    strip = Image.new('RGBA',(256,64))
    for i,(a,m) in enumerate(zip(cells,masks)):
        a[~m] = 0
        source = Image.fromarray(a)
        # Fixed source origin transform; empty margins and expansion survive intact.
        transform = (1/scale,0,cx-anchor[0]/scale,0,1/scale,cy-anchor[1]/scale)
        out = np.array(source.transform((64,64),Image.Transform.AFFINE,transform,Image.Resampling.BILINEAR))
        opaque = out[:,:,3] >= 175
        colors = out[opaque,:3].astype(int)
        if len(colors):
            d = ((colors[:,None,:]-palette[None,:,:])**2).sum(2)
            out[opaque,:3] = palette[d.argmin(1)]
        out[:,:,3] = opaque*255; out[~opaque,:3] = 0
        strip.alpha_composite(Image.fromarray(out),(i*64,0))
    strip.save(DEST/(name+'.png'))
    if name == 'huntingblade': anchor = [56,32]
    return strip,anchor

def main():
    DEST.mkdir(parents=True,exist_ok=True)
    manifest = {}
    overview = Image.new('RGB',(640,IDS.__len__()*160),'#28343b'); draw = ImageDraw.Draw(overview)
    for row,name in enumerate(IDS):
        image,anchor = pack(name)
        extents=[]
        for i in range(4):
            frame=image.crop((i*64,0,(i+1)*64,64)); bbox=frame.getbbox()
            assert bbox and bbox[0]>0 and bbox[1]>0 and bbox[2]<64 and bbox[3]<64,(name,i,bbox)
            a=np.array(frame);y,x=np.where(a[:,:,3]>0)
            extents.append({'bbox':list(bbox),'radius':round(float(np.hypot(x-anchor[0],y-anchor[1]).max()),3)})
        manifest[name]={'file':name+'.png','size':64,'frames':4,'anchor':anchor,'extent':extents}
        draw.text((5,row*160+4),name,fill='#f1f3e5')
        overview.paste(image.resize((512,128),Image.Resampling.NEAREST),(90,row*160+22),image.resize((512,128),Image.Resampling.NEAREST))
        print(name,anchor,[e['bbox'] for e in extents])
    (DEST/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
    overview.save(DEST/'overview.png')
    (ROOT/'js/swordfxdata.js').write_text('// Generated by tools/pixel/build_sword_fx.py.\nwindow.SWORD_FX_ART='+json.dumps(manifest,separators=(',',':'))+';\n',encoding='utf-8')

if __name__=='__main__': main()
